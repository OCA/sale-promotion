import secrets
from collections import defaultdict

from odoo import api, fields, models
from odoo.http import request

REFERRAL_COOKIE = "sale_loyalty_referral_ref"
REFERRAL_SESSION_KEY = "referral_partner_id"

# Crockford-style alphabet: no 0/O, 1/I/L so codes are easy to type and read aloud.
_REFERRAL_CODE_ALPHABET = "ABCDEFGHJKMNPQRSTUVWXYZ23456789"
_REFERRAL_CODE_LENGTH = 8


class ResPartner(models.Model):
    _inherit = "res.partner"

    referral_code_ids = fields.One2many(
        "loyalty.referral",
        "partner_id",
        string="Referral Codes",
        help="This partner's referral links, one per referral program.",
    )
    referral_code = fields.Char(
        compute="_compute_referral_code",
        compute_sudo=True,
        help="Personal referral code from this partner's first referral link. "
        "Doubles as a promotion code inside the referral loyalty program.",
    )
    referral_url = fields.Char(
        compute="_compute_referral_url",
        help="Shareable referral link: the configured landing page plus the "
        "personal code as a ?referral= parameter.",
    )
    referral_count = fields.Integer(
        compute="_compute_referral_count",
        string="Referred Friends",
        help="Number of distinct customers who bought through this partner's "
        "referral link.",
    )

    @api.depends("referral_code_ids.code")
    def _compute_referral_code(self):
        for partner in self:
            partner.referral_code = partner.referral_code_ids[:1].code

    @api.depends("referral_code")
    def _compute_referral_url(self):
        base_url = self._get_referral_base_url()
        for partner in self:
            # Codes are opt-in: generated by the partner's portal button or the
            # partners list "Generate Referral Code" action, never on read.
            partner.referral_url = (
                f"{base_url}?referral={partner.referral_code}"
                if base_url and partner.referral_code
                else False
            )

    def _compute_referral_count(self):
        referred = self._get_referred_partners()
        for partner in self:
            partner.referral_count = len(referred.get(partner.id, ()))

    def _get_referred_partners(self):
        """Map each partner in self to the distinct customers their referral
        brought in. Integrations extend this with their own records."""
        referred = defaultdict(set)
        groups = self.env["sale.order"]._read_group(
            [
                ("referred_by_id", "in", self.ids),
                ("state", "in", ["sale", "done"]),
            ],
            ["referred_by_id"],
            ["partner_id:recordset"],
        )
        for referrer, customers in groups:
            referred[referrer.id] |= set(customers.ids)
        return referred

    @api.model
    def _get_referral_program(self):
        program_id = int(
            self.env["ir.config_parameter"]
            .sudo()
            .get_param("sale_loyalty_referral.referral_program_id")
            or 0
        )
        return (
            self.env["loyalty.program"]
            .sudo()
            .browse(program_id)
            .exists()
            .filtered("active")
        )

    @api.model
    def _get_referral_base_url(self):
        if not self._get_referral_program():
            return False
        program = self._get_referral_program()
        config = self.env["ir.config_parameter"].sudo().get_param
        base = (
            program.referral_base_url
            or config("sale_loyalty_referral.referral_base_url")
            or "/"
        )
        return f"{config('web.base.url')}{base}"

    @api.model
    def _get_referral_partner(self):
        """Partner whose code was captured on this request, from the session or
        the long-lived cookie. Empty outside an HTTP request."""
        try:
            session = request.session
        except RuntimeError:
            return self.env["res.partner"]
        partner_id = session.get(REFERRAL_SESSION_KEY)
        if partner_id:
            return self.sudo().browse(partner_id).exists()
        partner = self._get_partner_by_referral_code(
            request.httprequest.cookies.get(REFERRAL_COOKIE)
        )
        if partner:
            session[REFERRAL_SESSION_KEY] = partner.id
        return partner

    @api.model
    def _get_partner_by_referral_code(self, code):
        if not code:
            return self.env["res.partner"]
        link = (
            self.env["loyalty.referral"]
            .sudo()
            .search([("code", "=", code.strip().upper())], limit=1)
        )
        return link.partner_id

    def ensure_referral_code(self, program=False):
        """Mint this partner's referral link (code + loyalty rule) in the
        given or configured program. Returns the code, or False when no
        referral program is configured."""
        self.ensure_one()
        program = program or self._get_referral_program()
        if not program:
            return False
        link = self.referral_code_ids.filtered(lambda r: r.program_id == program)[:1]
        if link:
            return link.code
        code = False
        for _try in range(100):
            candidate = self._new_referral_code()
            if not self.env["loyalty.referral"].search_count(
                [("code", "=", candidate)]
            ):
                code = candidate
                break
        if not code:
            raise RuntimeError("Could not generate a unique referral code.")
        rule = self._ensure_referral_rule(program)
        self.env["loyalty.referral"].sudo().create(
            self._prepare_loyalty_referral_values(program, rule, code)
        )
        return code

    def _prepare_loyalty_referral_values(self, program, rule, code):
        self.ensure_one()
        return {
            "partner_id": self.id,
            "program_id": program.id,
            "rule_id": rule.id,
            "code": code,
        }

    def _ensure_referral_rule(self, program):
        # One shared promotion rule per referral program: every minted
        # referral code aliases it, so code data stays out of the program's
        # rule configuration.
        self.ensure_one()
        Rule = self.env["loyalty.rule"].sudo()
        rule = Rule.search(
            [
                ("program_id", "=", program.id),
                ("mode", "=", "with_code"),
                ("is_referral_rule", "=", True),
            ],
            limit=1,
        )
        if not rule:
            rule = Rule.create(self._referral_rule_vals(program))
        return rule

    def _referral_rule_vals(self, program):
        """Values for the program's shared referral rule. Extend to add
        conditions applied to every referral code of the program."""
        self.ensure_one()
        return {
            "program_id": program.id,
            "mode": "with_code",
            "code": self._new_referral_code(),
            "is_referral_rule": True,
        }

    @api.model
    def _new_referral_code(self):
        """Return a candidate referral code (uniqueness is checked by the
        caller). Override to customize the code format."""
        return "".join(
            secrets.choice(_REFERRAL_CODE_ALPHABET)
            for _i in range(_REFERRAL_CODE_LENGTH)
        )
